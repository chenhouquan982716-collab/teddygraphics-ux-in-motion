"""Trace the TeddyGraphix bear mark out of a reference outro frame into an SVG path.

This is the tool that produced `src/logo-path.ts`. It needs the reference video's
frames extracted first:

    ffmpeg -i reference.mp4 -vsync 0 -q:v 2 frames/f%04d.jpg

then point FRAME_GLOB at them and run:

    python tools/trace-logo.py

The frame is upscaled 2x, thresholded, the contours are converted to
Catmull-Rom -> cubic Beziers and emitted as one even-odd path (holes included),
so the mark renders as a single crisp <path> at any size.
"""
import glob, json, sys
import numpy as np
import cv2
from PIL import Image, ImageDraw

FRAME_GLOB = 'frames/f*.jpg'
FRAME_INDEX = 359          # the clean lockup, one second before the fade out
SCALE = 2                  # work at 2x for smoother contours
OUT = 'src/logo-path.ts'
PREVIEW = 'trace-preview.png'

FR = sorted(glob.glob(FRAME_GLOB))
if not FR:
    sys.exit('no frames found - extract them first (see module docstring)')

img = Image.open(FR[FRAME_INDEX]).convert('L')
img = img.resize((img.width * SCALE, img.height * SCALE), Image.LANCZOS)
a = np.asarray(img, dtype=np.float32) / 255.0
H, W = a.shape
mask = (a > 0.42).astype(np.uint8)

# locate the pill: long horizontal runs of white in the lower third
rowsum = mask[int(H * 0.6):].sum(1)
ys = np.arange(int(H * 0.6), H)
cand = ys[rowsum > W * 0.28]
y_cut = int(cand.min()) - 2 if len(cand) else int(H * 0.66)
print('pill top row (2x px):', y_cut, 'of', H)

head = mask.copy()
head[y_cut:] = 0
ys_, xs_ = np.nonzero(head)
y0, y1, x0, x1 = ys_.min(), ys_.max(), xs_.min(), xs_.max()
print('mark bbox', x0, y0, x1, y1)

head = head[y0:y1 + 1, x0:x1 + 1]
head = cv2.morphologyEx(head, cv2.MORPH_CLOSE, np.ones((3, 3), np.uint8))

contours, hier = cv2.findContours(head, cv2.RETR_CCOMP, cv2.CHAIN_APPROX_NONE)
hier = hier[0]
print('contours', len(contours))


def catmull(pts):
    """Closed catmull-rom -> cubic bezier path."""
    n = len(pts)
    if n < 4:
        return ''
    d = 'M %.2f %.2f' % (pts[0][0], pts[0][1])
    for i in range(n):
        p0 = pts[(i - 1) % n]
        p1 = pts[i]
        p2 = pts[(i + 1) % n]
        p3 = pts[(i + 2) % n]
        c1 = (p1[0] + (p2[0] - p0[0]) / 6.0, p1[1] + (p2[1] - p0[1]) / 6.0)
        c2 = (p2[0] - (p3[0] - p1[0]) / 6.0, p2[1] - (p3[1] - p1[1]) / 6.0)
        d += ' C %.2f %.2f %.2f %.2f %.2f %.2f' % (c1[0], c1[1], c2[0], c2[1], p2[0], p2[1])
    return d + ' Z'


def path_from(contours, min_area=6.0):
    out = []
    for c in contours:
        if cv2.contourArea(c) < min_area:
            continue
        ap = cv2.approxPolyDP(c, 1.2, True).reshape(-1, 2)
        if len(ap) < 4:
            continue
        out.append(catmull([(float(p[0]), float(p[1])) for p in ap]))
    return ' '.join(out)


# silhouette = outer contours only (parent == -1)
outer = [c for c, h in zip(contours, hier) if h[3] == -1]
sil = path_from(outer, min_area=60)
det = path_from(contours, min_area=4)

w = x1 - x0 + 1
h = y1 - y0 + 1
print('mark size at 2x', w, h)

ts = (
    '// AUTO-GENERATED by tools/trace-logo.py - vector trace of the TeddyGraphix mark.\n'
    'export const LOGO = {\n'
    f'  width: {w},\n  height: {h},\n'
    f'  silhouette: {json.dumps(sil)},\n'
    f'  detail: {json.dumps(det)},\n'
    '} as const;\n'
)
with open(OUT, 'w', encoding='utf-8') as f:
    f.write(ts)
print('wrote', OUT, len(sil) + len(det), 'bytes of path data')

preview = Image.new('RGB', (w + 8, h + 8), (23, 24, 27))
dr = ImageDraw.Draw(preview)
for c in contours:
    if cv2.contourArea(c) < 4:
        continue
    pts = [(int(p[0][0]) + 4, int(p[0][1]) + 4) for p in c]
    dr.line(pts + [pts[0]], fill=(240, 240, 240), width=1)
preview = preview.resize((preview.width * 2, preview.height * 2), Image.LANCZOS)
preview.save(PREVIEW)
print('wrote', PREVIEW, preview.size)
