// Copies the self-hosted woff2 files used by the composition out of @fontsource/*.
// Run once: npm i --no-save @fontsource/inter @fontsource/instrument-serif @fontsource/ibm-plex-mono && node scripts/copy-fonts.mjs
import fs from 'node:fs/promises';
import path from 'node:path';

const OUT = path.resolve('public/fonts');
const picks = [
  ['@fontsource/inter', 'inter-latin-400-normal.woff2', 'Inter', '400', 'normal'],
  ['@fontsource/inter', 'inter-latin-500-normal.woff2', 'Inter', '500', 'normal'],
  ['@fontsource/inter', 'inter-latin-600-normal.woff2', 'Inter', '600', 'normal'],
  ['@fontsource/inter', 'inter-latin-700-normal.woff2', 'Inter', '700', 'normal'],
  ['@fontsource/inter', 'inter-latin-800-normal.woff2', 'Inter', '800', 'normal'],
  ['@fontsource/inter', 'inter-latin-900-normal.woff2', 'Inter', '900', 'normal'],
  ['@fontsource/instrument-serif', 'instrument-serif-latin-400-normal.woff2', 'Instrument Serif', '400', 'normal'],
  ['@fontsource/instrument-serif', 'instrument-serif-latin-400-italic.woff2', 'Instrument Serif', '400', 'italic'],
  ['@fontsource/ibm-plex-mono', 'ibm-plex-mono-latin-400-normal.woff2', 'IBM Plex Mono', '400', 'normal'],
  ['@fontsource/ibm-plex-mono', 'ibm-plex-mono-latin-500-normal.woff2', 'IBM Plex Mono', '500', 'normal'],
  ['@fontsource/ibm-plex-mono', 'ibm-plex-mono-latin-600-normal.woff2', 'IBM Plex Mono', '600', 'normal'],
];

await fs.mkdir(OUT, { recursive: true });
const entries = [];
for (const [pkg, file, family, weight, style] of picks) {
  const src = path.resolve('node_modules', pkg, 'files', file);
  const buf = await fs.readFile(src);
  await fs.writeFile(path.join(OUT, file), buf);
  entries.push({ family, weight, style, file, bytes: buf.length });
}

const lines = [
  '// AUTO-GENERATED by scripts/copy-fonts.mjs — do not edit by hand.',
  '// Latin subset, self-hosted so renders are reproducible offline.',
  'export const FONT_FILES = [',
  ...entries.map(
    (e) =>
      `  {family: ${JSON.stringify(e.family)}, weight: ${JSON.stringify(e.weight)}, style: ${JSON.stringify(e.style)}, file: ${JSON.stringify('fonts/' + e.file)}},`,
  ),
  '] as const;',
  '',
];
await fs.writeFile('src/fonts.generated.ts', lines.join('\n'));
console.log(entries.map((e) => `${e.family} ${e.weight} ${e.style} ${e.file} ${e.bytes}b`).join('\n'));
